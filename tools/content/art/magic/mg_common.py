def seed(rec, salt=''):
    return zlib.crc32((rec['id'] + salt).encode())


def new():
    s = Sprite(); s.shadow = False
    return s


def clear(s, shape, box):
    """punch a transparent hole"""
    if shape == 'ell': s.d.ellipse(box, fill=(0, 0, 0, 0))
    elif shape == 'poly': s.d.polygon(box, fill=(0, 0, 0, 0))
    else: s.d.rectangle(box, fill=(0, 0, 0, 0))


def col(rec, default):
    c = rec.get('color')
    return tuple(c[:3]) if c else default


def vivid(c, lo=70):
    """lift a dull/dark data colour so the sprite is not a muddy blob"""
    m = max(c)
    if m < lo:
        k = lo / max(m, 1)
        c = tuple(min(255, int(v * k) + 10) for v in c)
    return tuple(c)


def mix(a, b, t):
    return tuple(int(a[i] * (1 - t) + b[i] * t) for i in range(3))


def chain(s, pts, c, c2=None):
    """dotted chain along a polyline"""
    c2 = c2 or shade(c, -1)
    n = 0
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        steps = max(abs(x1 - x0), abs(y1 - y0))
        for i in range(steps + 1):
            x = round(x0 + (x1 - x0) * i / max(steps, 1)); y = round(y0 + (y1 - y0) * i / max(steps, 1))
            s.px([(x, y)], c if n % 2 == 0 else c2); n += 1



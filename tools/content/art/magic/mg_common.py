def M(s, name, cx, cy, c, c2=None, c3=None, scale=1):
    rows = MOTIFS[name]
    if scale != 1:
        h0, w0 = len(rows), max(len(r) for r in rows)
        rows = [''.join(rows[int(j / scale)].ljust(w0, '.')[int(i / scale)] for i in range(round(w0 * scale)))
                for j in range(round(h0 * scale))]
    c2 = c2 or shade(c, 2); c3 = c3 or shade(c, -2)
    h, w = len(rows), max(len(r) for r in rows)
    x0, y0 = cx - w // 2, cy - h // 2
    for j, r in enumerate(rows):
        for i, ch in enumerate(r):
            if ch == '.': continue
            s.px([(x0 + i, y0 + j)], c if ch == '#' else (c2 if ch == 'o' else c3))



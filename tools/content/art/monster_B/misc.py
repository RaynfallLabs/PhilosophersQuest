def beholder(s, c, iris, stalks, rad=9, cy=17, mouth=True, stalkeye=None):
    pts = {4: (-9, -3, 3, 9), 6: (-11, -7, -3, 3, 7, 11), 10: (-13, -10, -7, -4, -1, 2, 5, 8, 11, 14)}[stalks]
    for k, dx in enumerate(pts):
        x0 = 16 + dx * (rad - 2) // 12; y0 = cy - rad + 2
        x1 = 16 + dx; y1 = max(2, cy - rad - 5 + abs(dx) // 3 + (k % 2) * 2)
        s.l([(x0, y0), (x1, y1 + 2), (x1, y1)], mul(c, 0.85))
        e = stalkeye[k % len(stalkeye)] if stalkeye else iris
        s.r(x1 - 1, y1 - 1, x1 + 1, y1 + 1, WHITE if not stalkeye else e); s.px([(x1, y1)], BLACK if stalkeye else e)
    s.e(16 - rad, cy - rad, 15 + rad, cy + rad - 1, c)
    er = rad // 2 + 1
    s.e(16 - er, cy - er - 1, 15 + er, cy + er - 3, WHITE)
    s.e(14, cy - 4, 17, cy - 1, iris); s.px([(15, cy - 3), (16, cy - 2)], BLACK)
    if mouth:
        s.r(16 - rad + 3, cy + rad - 5, 15 + rad - 3, cy + rad - 4, BLACK)
        for x in range(16 - rad + 3, 15 + rad - 2, 2):
            s.px([(x, cy + rad - 5)], WHITE)
    s.shadow = True



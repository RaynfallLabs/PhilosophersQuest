def skel(s, bone=BONE, eye=None, mail=None, arms=True, gut=None):
    s.l([(13, 23), (13, 28)], bone, 2); s.l([(18, 23), (18, 28)], bone, 2)
    s.r(12, 28, 15, 29, bone); s.r(17, 28, 20, 29, bone)
    s.p([(12, 20), (19, 20), (18, 23), (13, 23)], bone)
    s.r(11, 12, 20, 19, gut or DARK)
    for y in (12, 14, 16, 18):
        s.l([(11, y), (20, y)], bone)
    s.l([(15, 11), (15, 21)], bone, 2)
    if mail:
        s.r(11, 12, 20, 18, mail); s.l([(11, 15), (20, 15)], mul(mail, 0.7))
        s.px([(12, 19), (14, 19), (17, 19), (19, 19)], mail)
    if arms:
        s.l([(10, 12), (8, 16), (8, 21)], bone); s.l([(21, 12), (23, 16), (23, 20)], bone)
    skull(s, bone, 11, 2, eye)



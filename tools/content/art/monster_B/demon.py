def fiend(s, skin, eye, big=False, wings=None, horn='long', hornc=BONE, tail_='barb', cloth=None,
          armor=None, hoof=DARK, hy=None, span=None, fang=True):
    if wings:
        bat_wings(s, wings[0], wings[1], y=11 if big else 13, span=span or (13 if big else 10), drop=11 if big else 9,
                  root=10 if big else 11)
    if tail_:
        tail(s, skin, 1, 23, tip=tail_)
    if big:
        hy = 2 if hy is None else hy
        s.mr(10, 22, 14, 27, mul(skin, 0.82)); s.mr(9, 28, 14, 29, hoof)
        s.p([(7, 10), (24, 10), (21, 22), (10, 22)], skin)
        s.me(9, 12, 15, 16, mul(skin, 1.14)); s.l([(15, 17), (15, 21)], mul(skin, 0.7)); s.l([(12, 19), (19, 19)], mul(skin, 0.7))
        s.mr(4, 11, 7, 19, mul(skin, 0.9)); s.mr(4, 20, 7, 23, skin)
        if cloth:
            s.p([(10, 20), (21, 20), (19, 26), (15, 24), (12, 26)], cloth)
        if armor:
            s.p([(8, 10), (23, 10), (21, 19), (10, 19)], armor); s.me(3, 8, 9, 13, mul(armor, 1.25))
            s.l([(15, 11), (15, 18)], mul(armor, 0.7)); s.l([(16, 11), (16, 18)], mul(armor, 0.7))
        s.e(12, hy, 19, hy + 8, skin)
        horns(s, hornc, horn, hy, 13)
        s.mpx([(14, hy + 4)], eye); s.l([(14, hy + 7), (17, hy + 7)], DARK)
        if fang:
            s.px([(14, hy + 8), (17, hy + 8)], WHITE)
        return {'r': 27, 'l': 4}
    hy = 3 if hy is None else hy
    s.mr(12, 22, 14, 27, mul(skin, 0.82)); s.mr(11, 28, 14, 29, hoof)
    s.r(11, 12, 20, 22, skin); s.l([(15, 13), (15, 19)], mul(skin, 0.75)); s.l([(12, 16), (19, 16)], mul(skin, 0.75))
    s.mr(8, 12, 10, 19, mul(skin, 0.9)); s.mr(8, 20, 10, 21, skin)
    if cloth:
        s.p([(11, 20), (20, 20), (19, 25), (16, 23), (12, 25)], cloth)
    if armor:
        s.r(11, 12, 20, 19, armor); s.me(7, 10, 11, 14, mul(armor, 1.25)); s.l([(15, 13), (15, 18)], mul(armor, 0.7))
    s.r(14, hy + 7, 17, 12, skin); s.e(11, hy, 20, hy + 8, skin)
    horns(s, hornc, horn, hy, 12)
    s.mpx([(13, hy + 4)], eye); s.l([(14, hy + 7), (17, hy + 7)], DARK)
    if fang:
        s.px([(14, hy + 8), (17, hy + 8)], WHITE)
    return {'r': 25, 'l': 5}



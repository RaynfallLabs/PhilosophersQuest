def imp(s, skin, eye, wings=True, tip='sting', wingc=None, hornc=BONE, belly=None, ears=True):
    wingc = wingc or mul(skin, 0.62)
    if wings:
        s.mp([(12, 16), (6, 8), (2, 9), (2, 17), (5, 15), (7, 19), (9, 16), (11, 19)], wingc)
        s.ml([(12, 16), (6, 8), (2, 9)], mul(skin, 0.8))
    s.l([(19, 24), (24, 26), (27, 23), (27, 18)], skin)
    if tip == 'sting':
        s.p([(27, 14), (25, 18), (29, 18)], skin)
    elif tip == 'barb':
        s.px([(26, 17), (28, 17), (27, 16), (27, 15)], skin)
    elif tip == 'fire':
        pass
    s.mr(13, 24, 14, 27, mul(skin, 0.85)); s.mr(11, 28, 14, 29, mul(skin, 0.7))
    s.e(11, 15, 20, 25, skin)
    if belly:
        s.e(13, 18, 18, 24, belly)
    s.ml([(11, 18), (8, 21), (9, 23)], mul(skin, 0.9))
    s.e(10, 6, 21, 17, skin)
    if ears:
        s.mp([(11, 10), (6, 8), (11, 13)], skin)
    s.mp([(12, 8), (11, 3), (14, 7)], hornc)
    s.mr(13, 10, 14, 11, eye)
    s.l([(13, 14), (18, 14)], DARK); s.px([(13, 15), (18, 15)], WHITE)



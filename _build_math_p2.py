ALL_QUESTIONS: list[dict] = T1_QUESTIONS + T2_ALL + T3_ALL + T4_ALL


def validate(record: dict) -> tuple[str, dict[str, str]]:
    """Return ('PASS' | 'SOFT_WARN' | 'FAIL', gate_results)."""
    results: dict[str, str] = {}
    hard_fail = False
    soft_warn = False
    for name, fn in PER_QUESTION_GATES:
        msg = fn(record)
        if msg:
            results[name] = msg
            if name in SOFT_WARN_GATES or msg.startswith("soft-warn"):
                soft_warn = True
            else:
                hard_fail = True
    if hard_fail:
        return "FAIL", results
    if soft_warn:
        return "SOFT_WARN", results
    return "PASS", results


def main() -> None:
    total = len(ALL_QUESTIONS)
    print(f"Total candidates: {total}")
    print(f"By tier: T1={sum(1 for q in ALL_QUESTIONS if q['tier']==1)}, "
          f"T2={sum(1 for q in ALL_QUESTIONS if q['tier']==2)}, "
          f"T3={sum(1 for q in ALL_QUESTIONS if q['tier']==3)}, "
          f"T4={sum(1 for q in ALL_QUESTIONS if q['tier']==4)}")

    passing: list[dict] = []
    soft_warn: list[dict] = []
    failed: list[tuple[int, dict, dict[str, str]]] = []

    for i, rec in enumerate(ALL_QUESTIONS):
        verdict, results = validate(rec)
        if verdict == "PASS":
            passing.append(rec)
        elif verdict == "SOFT_WARN":
            soft_warn.append(rec)
        else:
            failed.append((i, rec, results))

    print(f"\nPASS: {len(passing)}")
    print(f"SOFT_WARN: {len(soft_warn)}")
    print(f"FAIL: {len(failed)}")

    if failed:
        print("\n=== FAILURES ===")
        for i, rec, results in failed[:30]:
            fail_msgs = {k: v for k, v in results.items() if v and k not in SOFT_WARN_GATES and not v.startswith("soft-warn")}
            print(f"\n#{i} T{rec['tier']}: {rec['question']!r}")
            for k, v in fail_msgs.items():
                print(f"  [{k}] {v}")

    # Save passing + soft-warn records
    saved = passing + soft_warn
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(saved, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"\nSaved {len(saved)} records to {OUTPUT}")


if __name__ == "__main__":
    main()
